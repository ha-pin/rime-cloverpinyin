#!/usr/bin/env python3
"""Generate supplemental Rime tables without changing source word spellings."""
import argparse
import hashlib
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RULES_VERSION = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
# Match the existing hapin_*_basic dictionaries, including their established keys.
ARABIC = dict(zip(
    "ابتجحدرزسشعفقكلمنوىيپچڭگھۆۇۋە",
    "a b t j h d r z s sh gh f q k l m n o e i p ch ng g hh v u w ye".split(),
))
CYRILLIC = dict(zip(
    "абвгдеёжзийклмнопрстуфхцчшщъыьэюяіғқңүұһәө",
    "a b v g d ye yo j z i i k l m n o p r s t w f h ts ch sh shsh xx e xy yy yw ya xe gh q ng xu u hh xa xo".split(),
))
# Kyrgyz Arabic letters retain the existing Hapin keyboard conventions.
# The three distinct vowels are u / xo (ö) / xu (ü); ئ represents i (xe).
KYRGYZ = {**ARABIC, "ۅ": "xo", "ۉ": "xu", "ئ": "xe"}
WEAK_VOWELS = {"a", "o", "u", "e"}


def encode(word, language, simplified=False):
    table = {"kazakh_arabic": ARABIC, "kazakh_cyrillic": CYRILLIC,
             "kyrgyz_arabic": KYRGYZ}[language]
    result = []
    weak = False
    for char in word.lower():
        if char == "ـ":  # Tatweel is decorative; retain it only in output text.
            continue
        if language == "kazakh_arabic" and char in "ٴء":
            weak = True
            continue
        if char not in table:
            raise ValueError(f"{language}: 无法编码 {word!r} 中的 {char!r}")
        key = table[char]
        if weak and key in WEAK_VOWELS:
            key = "x" + key
            weak = False
        if simplified and key in {"xa", "xo", "xu", "xe"}:
            key = key[1:]
        result.append(key)
    if weak:
        result.append("x")  # A trailing standalone hamza keeps the basic table's x key.
    code = "".join(result)
    if not re.fullmatch("[a-z]+", code):
        raise ValueError(f"{language}: 无效编码 {word!r}: {code!r}")
    return code


def codes(word, language, prefix):
    canonical = encode(word, language)
    # The original 3000-word tables also accept spellings without vowel modifiers.
    # Remove only vowel x, never the Cyrillic hard/soft sign keys xx and xy.
    simplified = encode(word, language, simplified=True)
    return {prefix + canonical, prefix + simplified}


def generate(source, output):
    manifest = json.loads((source / "manifest.json").read_text(encoding="utf-8"))
    word_lists = {}
    for language in ("kazakh_arabic", "kazakh_cyrillic", "kyrgyz_arabic"):
        filename = f"{language}.txt"
        data = (source / filename).read_bytes()
        if hashlib.sha256(data).hexdigest() != manifest[filename]["sha256"]:
            raise ValueError(f"{filename}: 源文件校验值不匹配，请核对 manifest.json")
        words = data.decode("utf-8-sig").splitlines()
        if len(words) != manifest[filename]["entries"] or any(not w or w != w.strip() for w in words):
            raise ValueError(f"{filename}: 条数不匹配或包含空行/首尾空白")
        word_lists[language] = words

    output.mkdir(parents=True, exist_ok=True)
    report = {}
    for name, languages, prefix in (
        ("hapin_arabic_desktop", ("kazakh_arabic", "kyrgyz_arabic"), "u"),
        ("hapin_cyrillic_desktop", ("kazakh_cyrillic",), "u"),
        ("hapin_mixed_cyrillic_desktop", ("kazakh_cyrillic",), "v"),
    ):
        raw_words = [word for language in languages for word in word_lists[language]]
        excluded = [word for word in raw_words if not word.strip("ـ")]
        words = [word for word in raw_words if word.strip("ـ")]
        entries = {(word, code) for language in languages
                   for word in word_lists[language] if word.strip("ـ")
                   for code in codes(word, language, prefix)}
        sources = ", ".join(f"vocabulary/{language}.txt" for language in languages)
        header = (f"# Generated by scripts/import_vocabulary.py; sources: {sources}\n"
                  f"---\nname: {name}\nversion: \"{RULES_VERSION}\"\nsort: by_weight\n"
                  "use_preset_vocabulary: false\n...\n")
        # No source frequencies are available: use equal, low weights.
        body = "".join(f"{word}\t{code}\t1\n" for word, code in sorted(entries, key=lambda row: (row[1], row[0])))
        (output / f"{name}.dict.yaml").write_text(header + body, encoding="utf-8")
        report[name] = {"rules_version": RULES_VERSION, "source_entries": len(raw_words), "unique_words": len(set(words)),
                        "excluded_nonwords": excluded,
                        "encoded_words": len({word for word, _ in entries}),
                        "entries_with_aliases": len(entries), "prefix": prefix}
        print(f"{name}: {len(set(words))} 个词，{len(entries)} 条编码，前缀 {prefix}")
    (output / "vocabulary-report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "vocabulary")
    parser.add_argument("--output", type=Path, default=ROOT / "cache")
    args = parser.parse_args()
    generate(args.source, args.output)
